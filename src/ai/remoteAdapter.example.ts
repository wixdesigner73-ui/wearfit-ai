import type { AdapterInfo, TryOnAdapter, TryOnRequest, TryOnResult } from './types'

const ENDPOINT = 'https://your-tryon-service.example.com/v1/try-on' // <- your own proxy

export const remoteAdapterExample: TryOnAdapter = {
  info: {
    id: 'remote-example',
    label: 'Remote try-on model (example)',
    mode: 'ai',
    uploadsPhoto: true,
    description: 'Sends the photo to a remote model. Requires explicit user consent.',
  } satisfies AdapterInfo,

  async isAvailable() {
    try {
      const res = await fetch(`${ENDPOINT}/health`, { method: 'GET' })
      return res.ok
    } catch {
      return false
    }
  },

  async run(request: TryOnRequest, signal?: AbortSignal): Promise<TryOnResult> {
    const body = new FormData()
    body.append('person', request.photo, 'person.jpg')
    body.append('garment', JSON.stringify(request.garment))

    const res = await fetch(ENDPOINT, { method: 'POST', body, signal })
    if (!res.ok) throw new Error(`Try-on service returned ${res.status}`)

    return {
      mode: 'ai',
      isAiGenerated: true, // only once you have verified the model really generates the image
      disclosure: 'Generated by a remote AI model. Your photo was sent to the service to create this image.',
      imageBlob: await res.blob(),
    }
  },
}
