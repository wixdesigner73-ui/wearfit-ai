export function getProduct(id: string): Product | undefined {
  return PRODUCTS.find((p) => p.id === id)
}

export function formatPrice(usd: number): string {
  const value = usd * (CURRENCY === 'USD' ? 1 : CURRENCY_RATE)
  try {
    return new Intl.NumberFormat('en-US', { style: 'currency', currency: CURRENCY, maximumFractionDigits: 0 }).format(value)
  } catch {
    // Unknown currency code in config: fall back to plain USD formatting rather than crashing.
    return `$${Math.round(usd)}`
  }
}

export function isSizeAvailable(product: Product, size: string): boolean {
  return product.stock !== 'out-of-stock' && !product.soldOutSizes?.includes(size)
}

